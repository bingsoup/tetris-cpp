int Pieces::GetPieceIndex(PieceType type)
{
    switch (type)
    {
        case PieceType::O: return 0;
        case PieceType::I: return 1;
        case PieceType::L: return 2;
        case PieceType::J: return 3;
        case PieceType::S: return 4;
        case PieceType::Z: return 5;
        case PieceType::T: return 6;
        default: return -1; // Invalid piece type
    }
}

Pieces::Piece& Pieces::GetPiece(int idx)
{
    return mPieces.at(idx).piece;
}

Pieces::PieceDefinition Pieces::GetPieceDef(int idx)
{
    return mPieces.at(idx);
}

char Pieces::GetPieceChar(int idx)
{
    return static_cast<char>(mPieces.at(idx).type);
}

int Pieces::GetNumPieces()
{
    return mPieces.size();
}